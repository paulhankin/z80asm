def die(face):
    pips = {1: [(7, 7)], 2: [(4, 10), (10, 4)], 3: [(3, 11), (7, 7), (11, 3)],
            4: [(4, 4), (4, 10), (10, 4), (10, 10)],
            5: [(3, 3), (3, 11), (7, 7), (11, 3), (11, 11)],
            6: [(4, 3), (4, 7), (4, 11), (10, 3), (10, 7), (10, 11)]}[face]
    g = [[' '] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            edge = x in (0, 15) or y in (0, 15)
            corner = (x in (0, 15) and y in (0, 15))
            if edge and not corner:
                g[y][x] = 'X'
    for (px, py) in pips:
        for dy in range(2):
            for dx in range(2):
                g[py + dy][px + dx] = 'X'
    return [''.join('X' if c == 'X' else '.' for c in row) for row in g]

def bits(row):
    v = 0
    for c in row:
        v = v * 2 + (1 if c == 'X' else 0)
    return v

def emit16(name, rows):
    print(f".{name}" if name.startswith('_') else f"{name}:")
    for r in rows:
        print(f"    db 0x{bits(r[:8]):02x}, 0x{bits(r[8:]):02x}   // {r}")

